const Anthropic = require('@anthropic-ai/sdk');

const client = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY });

const SAFETY_NOTE = `
Важно: ты не врач и не квалифицированный медицинский специалист. Не ставь диагнозы,
не давай медицинских рекомендаций при травмах/заболеваниях — в таких случаях советуй
обратиться к врачу или тренеру очно. Учитывай ограничения, которые указал пользователь,
и предупреждай о необходимости консультации со специалистом при сомнениях.
`;

async function askClaude(systemPrompt, userPrompt, maxTokens = 1500) {
  const resp = await client.messages.create({
    model: 'claude-sonnet-5',
    max_tokens: maxTokens,
    system: systemPrompt,
    messages: [{ role: 'user', content: userPrompt }],
  });
  return resp.content.map((b) => (b.type === 'text' ? b.text : '')).join('\n').trim();
}

async function generateTrainingPlan(profile) {
  const system = `Ты — тренер и наставник по заботе о теле, который помогает женщинам худеть
и возвращать лёгкость и подвижность через мягкий, устойчивый подход, а не через изнурительные
тренировки. Тон — тёплый, поддерживающий, без осуждения по поводу веса или формы тела.
Отвечай на русском языке, структурированно, используй Markdown (заголовки, списки).
${SAFETY_NOTE}
В конце плана обязательно добавь короткую пометку: "Это не медицинская рекомендация.
При наличии травм или заболеваний проконсультируйся с врачом."`;

  const user = `Составь план тренировок на неделю для человека со следующими параметрами:
- Цель: ${profile.goal}
- Текущий вес/замеры (если указаны): ${profile.currentStats || 'не указано'}
- Желаемый вес/направление изменений: ${profile.targetStats || 'не указано'}
- Уровень подготовки: ${profile.level}
- Доступное оборудование: ${profile.equipment}
- Количество тренировочных дней в неделю: ${profile.daysPerWeek}
- Ограничения/пожелания: ${profile.restrictions || 'нет'}

Для каждого дня укажи: название дня (например "День 1 — Лёгкость в теле"),
список упражнений с подходами/повторениями, короткое пояснение техники по каждому упражнению.`;

  return askClaude(system, user, 2000);
}

async function generateMealPlan(profile) {
  const system = `Ты — нутрициолог-ассистент, который помогает составлять простые планы питания
для похудения и заботы о теле без жёстких ограничений и чувства вины. Отвечай на русском языке,
структурированно, используй Markdown.
Не давай медицинских рекомендаций по лечению заболеваний; при пищевых ограничениях,
связанных со здоровьем, советуй свериться с врачом/диетологом.`;

  const user = `Составь простой план питания на 1 день и список покупок на неделю для человека с целью: "${profile.goal}".
Текущий вес/замеры: ${profile.currentStats || 'не указано'}. Желаемое направление: ${profile.targetStats || 'не указано'}.
Учти пожелания/ограничения: ${profile.restrictions || 'нет особых пожеланий'}.
Формат: приёмы пищи (завтрак/обед/ужин/перекусы) + отдельный список покупок на неделю.`;

  return askClaude(system, user, 1500);
}

async function getGeneralCheckupInfo(profile) {
  // ВАЖНО: это осознанно общая, образовательная информация — НЕ интерпретация
  // конкретных анализов пользователя и НЕ рекомендации по приёму добавок/препаратов
  // на основе его личных показателей. Бот не запрашивает и не анализирует цифры
  // из анализов пользователя — это было бы медицинской консультацией, которую
  // нельзя давать без врача.
  const system = `Ты — ассистент по общему велнесу. Дай общий образовательный список анализов,
которые люди обычно обсуждают с врачом перед стартом программы похудения/тренировок
(например: общий анализ крови, глюкоза, витамин D, железо/ферритин, гормоны щитовидной железы).
НЕ интерпретируй никакие конкретные результаты — у тебя их и нет. НЕ называй конкретные
препараты, добавки или дозировки. Обязательно подчеркни, что решение о том, что сдавать
и что пить/принимать по результатам, принимает врач, а не бот. Отвечай на русском, Markdown.`;

  const user = `Пользователь готовится к программе похудения. Дай общий (не персональный)
список анализов, которые стоит обсудить с врачом перед стартом, и почему они полезны для
понимания состояния организма. Не давай советов по приёму конкретных веществ.`;

  return askClaude(system, user, 900);
}

async function adjustPlan(profile, previousPlan, feedback) {
  const system = `Ты — тренер и наставник по заботе о теле (похудение, лёгкость движения),
который корректирует ранее составленный план тренировок на основе обратной связи пользователя.
Тон тёплый, без осуждения. Отвечай на русском языке, структурированно, Markdown.
${SAFETY_NOTE}`;

  const user = `Вот текущий план тренировок пользователя:
---
${previousPlan}
---
Обратная связь пользователя: "${feedback}"

Скорректируй план с учётом обратной связи. Если пользователь жалуется на боль или
дискомфорт — порекомендуй снизить нагрузку и обратиться к специалисту, не давай
медицинских советов.`;

  return askClaude(system, user, 2000);
}

module.exports = { generateTrainingPlan, generateMealPlan, adjustPlan, getGeneralCheckupInfo };
